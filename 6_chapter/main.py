# 27. REAL-WORLD EXAMPLE - STUDENT MARKS
# ============================================================
#
# Suppose we have student marks:
#
#     35, 42, 67, 80, 25, 90
# ============================================================

marks = np.array([35, 42, 67, 80, 25, 90])

print("\nStudent Marks:")
print(marks)


# ============================================================
# STUDENTS WHO SCORED MORE THAN 50
# ============================================================

print("\nMarks greater than 50:")
print(marks > 50)
# ============================================================
# STUDENTS WHO SCORED BETWEEN 40 AND 80
# ============================================================
print((marks >= 40) & (marks <= 80))

