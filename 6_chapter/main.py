import numpy as np

#     ELEMENT-WISE OPERATION
# ============================================================
a = np.array([10, 20, 30])
b = np.array([1, 2, 3])

print("Array a:")
print(a)

print("\nArray b:")
print(b)

# ============================================================
# 2. ADDITION +
# ============================================================

result = a  + b
print(result)

# ============================================================
# 3. SUBTRACTION -
# ============================================================

result = a-b
print(result)

# ============================================================
# 4. MULTIPLICATION *
# ============================================================
result = a*b
print(result)

# ============================================================
# 5. DIVISION /
# ============================================================

result = a/b
print(result)

# ============================================================
# 6. MODULUS %
# ============================================================
result = a%b
print(result)

# ============================================================
# MODULUS - ANOTHER EXAMPLE
# ============================================================

a_mod = np.array([10, 11, 12])
b_mod = np.array([3, 3, 5])

print("\nAnother Modulus Example:")
print(a_mod % b_mod)

# ============================================================
# 7. POWER **
# ============================================================

power_arr = np.array([2, 3, 4])

print(power_arr ** 2)

# ============================================================
# 8. ARRAY + ARRAY POWER
# ============================================================

a_power = np.array([2, 3, 4])
b_power = np.array([2, 3, 2])

print(a_power ** b_power)

# ============================================================
# 10. SCALAR OPERATIONS
# ============================================================

arr = np.array([10, 20, 30])
print(arr)

# ============================================================
# ADD 5
# ============================================================
print(arr+5)

# ============================================================
# SUBTRACT 5
# ============================================================
print(arr-5)

# ============================================================
# MULTIPLY BY 2
# ============================================================
print(arr*2)

# ============================================================
# DIVIDE BY 10
# ============================================================
print(arr/10)

# ============================================================
# POWER 2
# ============================================================
print(arr**2)

# ============================================================
# 12. COMPARISON OPERATORS
# ============================================================

arr = np.array([10, 20, 30, 40])

print("\nComparison Array:")
print(arr)

# ============================================================
# 13. GREATER THAN >
# ============================================================
print(arr>25)

# ============================================================
# 14. LESS THAN <
# ============================================================
print(arr<25)

# ============================================================
# 15. GREATER THAN OR EQUAL >=
# ============================================================

print(arr>=30)

# ============================================================
# 16. LESS THAN OR EQUAL <=
# ============================================================

print(arr <= 30)

# ============================================================
# 17. EQUAL ==
# ============================================================

print("\nEqual to 30:")
print(arr == 30)

# ============================================================
# 18. NOT EQUAL !=
# ============================================================

print("\nNot equal to 30:")
print(arr != 30)

# ============================================================
# 20. COMPARING TWO ARRAYS
# ============================================================
a_compare = np.array([10, 20, 30])
b_compare = np.array([10, 25, 20])

print("\nCompare Two Arrays:")
print(a_compare > b_compare)

# ============================================================
# 21. LOGICAL OPERATIONS
# ============================================================
arr = np.array([10, 20, 30, 40, 50])

result = (arr > 15) & (arr < 45)

print("\nAND condition:")
print(result)

# ============================================================
# 24. OR |
# ============================================================
arr = np.array([10, 20, 30, 40, 50])

result = (arr < 15) | (arr > 45)

print("\nOR condition:")
print(result)
# ============================================================
# OR - DRY RUN
# ============================================================
arr = np.array([10, 20, 30, 40])

condition = arr > 25

print("\nOriginal condition:")
print(condition)
print("\nNOT condition:")
print(~condition)
